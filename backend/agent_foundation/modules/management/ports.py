from __future__ import annotations

from typing import Any, Protocol

from agent_foundation.kernel.primitives import ScopeRef

from .contracts import (
    EvaluationReport,
    ExtractorCertificate,
    ExtractorCertificateRevocation,
    ExtractorExecutionReceipt,
    IndexGeneration,
    ManagedRelease,
    ManagementOperationReceipt,
    TransferPlan,
)


class ReleaseEffect(Protocol):
    def validate(self, release: ManagedRelease) -> None: ...
    def activate(self, release: ManagedRelease, *, operation_id: str) -> dict[str, Any]: ...


class IndexEffect(Protocol):
    def verify(self, generation: IndexGeneration) -> dict[str, Any]: ...
    def activate(self, generation: IndexGeneration, *, operation_id: str) -> dict[str, Any]: ...


class TransferEffect(Protocol):
    def execute(self, plan: TransferPlan, *, operation_id: str) -> dict[str, Any]: ...


class ManagementAuthority(Protocol):
    def save_extractor_certificate(self, certificate: ExtractorCertificate, *, operation_id: str, command_digest: str) -> ExtractorCertificate: ...
    def get_extractor_certificate(self, scope: ScopeRef, certificate_id: str) -> ExtractorCertificate | None: ...
    def get_release_certificate(self, scope: ScopeRef, release_id: str) -> ExtractorCertificate | None: ...
    def revoke_extractor_certificate(self, revocation: ExtractorCertificateRevocation, *, operation_id: str, command_digest: str) -> ExtractorCertificateRevocation: ...
    def get_extractor_revocation(self, scope: ScopeRef, certificate_id: str) -> ExtractorCertificateRevocation | None: ...
    def save_extractor_execution(self, receipt: ExtractorExecutionReceipt, *, operation_id: str, command_digest: str) -> ExtractorExecutionReceipt: ...
    def get_extractor_execution(self, scope: ScopeRef, event_id: str) -> ExtractorExecutionReceipt | None: ...
    def get_extractor_execution_digest(self, scope: ScopeRef, event_id: str) -> str | None: ...
    def stage_release(self, release: ManagedRelease, *, operation_id: str, command_digest: str) -> ManagedRelease: ...
    def get_release(self, scope: ScopeRef, release_id: str) -> ManagedRelease | None: ...
    def list_releases(self, scope: ScopeRef, *, kind: str | None, status: str | None, limit: int) -> tuple[ManagedRelease, ...]: ...
    def get_active_release(self, scope: ScopeRef, kind: str, artifact_id: str) -> ManagedRelease | None: ...
    def approve_release(self, scope: ScopeRef, release_id: str, *, expected_revision: int, approved_by: str, operation_id: str, command_digest: str) -> ManagedRelease: ...
    def activate_release(self, scope: ScopeRef, release_id: str, *, expected_revision: int, activated_by: str, effect_receipt: dict[str, Any], operation_id: str, command_digest: str) -> ManagedRelease: ...
    def fail_release(self, scope: ScopeRef, release_id: str, *, expected_revision: int, error_code: str) -> ManagedRelease: ...
    def begin_index(self, generation: IndexGeneration, *, operation_id: str, command_digest: str) -> IndexGeneration: ...
    def get_index(self, scope: ScopeRef, generation_id: str) -> IndexGeneration | None: ...
    def list_indexes(self, scope: ScopeRef, *, domain: str | None, status: str | None, limit: int) -> tuple[IndexGeneration, ...]: ...
    def get_active_index(self, scope: ScopeRef, domain: str) -> IndexGeneration | None: ...
    def verify_index(self, scope: ScopeRef, generation_id: str, *, expected_revision: int, effect_receipt: dict[str, Any], operation_id: str, command_digest: str) -> IndexGeneration: ...
    def activate_index(self, scope: ScopeRef, generation_id: str, *, expected_revision: int, activated_by: str, effect_receipt: dict[str, Any], operation_id: str, command_digest: str) -> IndexGeneration: ...
    def fail_index(self, scope: ScopeRef, generation_id: str, *, expected_revision: int, error_code: str) -> IndexGeneration: ...
    def record_evaluation(self, report: EvaluationReport, *, operation_id: str, command_digest: str) -> EvaluationReport: ...
    def get_evaluation(self, scope: ScopeRef, evaluation_id: str) -> EvaluationReport | None: ...
    def list_evaluations(self, scope: ScopeRef, *, subject_ref: str | None, limit: int) -> tuple[EvaluationReport, ...]: ...
    def propose_transfer(self, plan: TransferPlan, *, operation_id: str, command_digest: str) -> TransferPlan: ...
    def get_transfer(self, scope: ScopeRef, transfer_id: str) -> TransferPlan | None: ...
    def list_transfers(self, scope: ScopeRef, *, kind: str | None, status: str | None, limit: int) -> tuple[TransferPlan, ...]: ...
    def approve_transfer(self, scope: ScopeRef, transfer_id: str, *, expected_revision: int, approved_by: str, operation_id: str, command_digest: str) -> TransferPlan: ...
    def complete_transfer(self, scope: ScopeRef, transfer_id: str, *, expected_revision: int, executed_by: str, effect_receipt: dict[str, Any], operation_id: str, command_digest: str) -> TransferPlan: ...
    def fail_transfer(self, scope: ScopeRef, transfer_id: str, *, expected_revision: int, error_code: str) -> TransferPlan: ...
    def diagnostics(self, scope: ScopeRef) -> dict[str, Any]: ...
    def get_receipt(self, scope: ScopeRef, operation_id: str) -> ManagementOperationReceipt | None: ...
    def close(self) -> None: ...
