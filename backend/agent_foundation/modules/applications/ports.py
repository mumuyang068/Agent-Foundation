from __future__ import annotations

from typing import Protocol

from agent_foundation.kernel.primitives import ResourceRef, ScopeRef

from .contracts import AgentTurn, TurnOperationReceipt


class TurnAuthority(Protocol):
    def create(self, turn: AgentTurn, *, operation_id: str, command_digest: str) -> AgentTurn: ...
    def get(self, scope: ScopeRef, turn_id: str) -> AgentTurn | None: ...
    def record_observation(self, turn: AgentTurn, *, expected_revision: int, operation_id: str, command_digest: str) -> AgentTurn: ...
    def record_outcome(self, turn: AgentTurn, *, expected_revision: int, operation_id: str, command_digest: str) -> AgentTurn: ...
    def get_receipt(self, scope: ScopeRef, operation_id: str) -> TurnOperationReceipt | None: ...
    def close(self) -> None: ...


class MemoryTurnPort(Protocol):
    def propose(self, token: str, *, content: str, source_refs: tuple[ResourceRef, ...], operation_id: str): ...
    def feedback(self, token: str, memory_id: str, *, expected_revision: int, value: float, operation_id: str): ...
    def get(self, token: str, memory_id: str): ...


class ContextTurnPort(Protocol):
    def assemble(self, token: str, **kwargs): ...
