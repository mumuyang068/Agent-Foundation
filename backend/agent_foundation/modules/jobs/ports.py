from __future__ import annotations

from datetime import datetime
from typing import Any, Protocol

from agent_foundation.kernel.primitives import ScopeRef

from .contracts import JobOperationReceipt, JobOutboxEvent, JobStepResult, ManagedJob


class JobFence(Protocol):
    @property
    def token(self) -> str: ...

    def check(self) -> None: ...


class JobHandler(Protocol):
    def __call__(
        self, payload: dict[str, Any], cursor: str | None, fence: JobFence
    ) -> JobStepResult: ...


class JobAuthority(Protocol):
    def plan(self, job: ManagedJob, *, operation_id: str, command_digest: str) -> ManagedJob: ...
    def get(self, scope: ScopeRef, job_id: str) -> ManagedJob | None: ...
    def list(self, scope: ScopeRef, *, limit: int) -> tuple[ManagedJob, ...]: ...
    def authorize(self, scope: ScopeRef, job_id: str, *, expected_revision: int, operation_id: str, command_digest: str) -> ManagedJob: ...
    def claim(self, scope: ScopeRef, job_id: str, *, worker_id: str, lease_seconds: int, now: datetime, max_attempts: int) -> ManagedJob: ...
    def assert_lease(self, scope: ScopeRef, job_id: str, *, lease_token: str, now: datetime) -> ManagedJob: ...
    def finish_step(self, scope: ScopeRef, job_id: str, *, lease_token: str, step: JobStepResult, now: datetime) -> ManagedJob: ...
    def fail_step(self, scope: ScopeRef, job_id: str, *, lease_token: str, error_code: str, retryable: bool, now: datetime) -> ManagedJob: ...
    def cancel(self, scope: ScopeRef, job_id: str, *, operation_id: str, command_digest: str, now: datetime) -> ManagedJob: ...
    def get_receipt(self, scope: ScopeRef, operation_id: str) -> JobOperationReceipt | None: ...
    def list_outbox(self, scope: ScopeRef, *, limit: int) -> tuple[JobOutboxEvent, ...]: ...
    def acknowledge_outbox(self, scope: ScopeRef, event_id: str) -> JobOutboxEvent: ...
    def close(self) -> None: ...
